import type { RawQuestion } from "./types";

const S = (
  content: string,
  correct: string,
  wrong: [string, string, string],
  analysis: string,
  chapterName: string,
  kpNames: string[],
  difficulty: 1 | 2 = 1,
): RawQuestion => ({
  type: 1,
  content,
  analysis,
  difficulty,
  semester: 2,
  chapterName,
  kpNames,
  options: [
    { key: "A", content: correct, isCorrect: true },
    { key: "B", content: wrong[0], isCorrect: false },
    { key: "C", content: wrong[1], isCorrect: false },
    { key: "D", content: wrong[2], isCorrect: false },
  ],
});

